#!/usr/bin/env bash
# shellcheck disable=SC2034 # settings used by the scripts that source this file
# Shared settings and helpers of the acceptance-*.sh scripts. Source it; do not run it.
#
# The acceptance stack is a second, isolated copy of the MVP stack: its own database container, data directory,
# secrets, systemd --user units (sunnycloud-acc-*), binaries and loopback ports. It reuses mvp-lib.sh for the
# process supervision and overrides only what names the MVP stack. Nothing here touches the MVP stack.

ACC_DATA="${ACC_DATA:-/develop/zxsanny/sunnycloud-acceptance}"
ACC_TARGET="${ACC_TARGET:-/develop/zxsanny/targets/acceptance}"
ACC_PORT_BASE="${ACC_PORT_BASE:-18800}"
ACC_DB_CONTAINER="sunnycloud-acc-db"
ACC_RESULTS="${ACC_RESULTS:-$ACC_DATA/results}"

# mvp-lib.sh reads these three at source time: data directory, secrets and the cargo target.
export MVP_DATA="$ACC_DATA" MVP_SECRETS="$ACC_DATA/secrets" CARGO_TARGET_DIR="$ACC_TARGET"
unset MVP_ENV_FILE MVP_COMPOSE MVP_RUN
# Nothing of the caller's own SUNNYCLOUD_* settings may leak into the units (start_process forwards them all).
while IFS= read -r name; do unset "$name"; done < <(compgen -e | grep '^SUNNYCLOUD_' || true)
# shellcheck source=mvp-lib.sh
# shellcheck source=mvp-lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/mvp-lib.sh"

log() { printf '[acc] %s\n' "$*"; }
die() { printf '[acc] ERROR: %s\n' "$*" >&2; exit 1; }

# The live MVP data and secrets must never be the acceptance ones: acceptance-down.sh deletes ACC_DATA.
[ "$(basename "$ACC_DATA")" = sunnycloud-acceptance ] || die "ACC_DATA must end in /sunnycloud-acceptance (it is deleted by acceptance-down.sh), got $ACC_DATA"
[ "$ACC_DATA" != /develop/zxsanny/sunnycloud-data ] || die "ACC_DATA is the live MVP data directory"

unit_of() { printf 'sunnycloud-acc-%s.service' "$1"; }

ACC_WEB_PORT="$ACC_PORT_BASE"
ACC_API_PORT=$((ACC_PORT_BASE + 1))
ACC_INTERNAL_PORT=$((ACC_PORT_BASE + 2))
ACC_OPS_PORT=$((ACC_PORT_BASE + 3))
ACC_WORKER_OPS_PORT=$((ACC_PORT_BASE + 4))
ACC_IDP_PORT=$((ACC_PORT_BASE + 5))
ACC_DB_PORT=$((ACC_PORT_BASE + 6))
# The host the browser opens. `localhost` is a secure context for Chromium (the Secure __Host- cookies work without TLS)
# and the web server listens on 127.0.0.1 only. Any other value (ACC_HOST=192.168.88.100) makes the web server listen on
# that address, so it is reachable from the LAN, over https with a self-signed certificate made for that address:
# Chromium keeps a Secure cookie only from https or localhost (its secure-origin flag does not change that).
# acceptance-up.sh records it in acceptance.env, so down, status and api-ctl address the stack the way it was started.
ACC_HOST="${ACC_HOST:-$(sed -n 's/^ACC_HOST=//p' "$ACC_DATA/acceptance.env" 2> /dev/null)}"
ACC_HOST="${ACC_HOST:-localhost}"
if [ "$ACC_HOST" = localhost ]; then ACC_SCHEME=http; else ACC_SCHEME=https; fi
ACC_ORIGIN="$ACC_SCHEME://$ACC_HOST:$ACC_WEB_PORT"
ACC_ISSUER="http://127.0.0.1:$ACC_IDP_PORT"
ACC_CLIENT_ID="sunnycloud-acceptance"
ACC_REDIRECT_URI="$ACC_ORIGIN/api/v1/auth/providers/oidc/callback"
ACC_PORTS=("$ACC_WEB_PORT" "$ACC_API_PORT" "$ACC_INTERNAL_PORT" "$ACC_OPS_PORT" "$ACC_WORKER_OPS_PORT" "$ACC_IDP_PORT" "$ACC_DB_PORT")
ACC_WEB_SRC="$ACC_TARGET/web"
ACC_WEB_DIST="$ACC_WEB_SRC/dist"
BUN="${BUN:-$(command -v bun || printf '%s/.bun/bin/bun' "$HOME")}"

# The environment file of the host processes (mvp-lib's load_env sources $MVP_SECRETS/mvp.env).
write_env_file() {
  cat > "$MVP_SECRETS/mvp.env" <<ENV
# Generated by acceptance-up.sh. development + allow_plain_http_dev are required for an http public_url and an
# http issuer: see _docs/04_deploy/acceptance.md.
SUNNYCLOUD_ENVIRONMENT=development
SUNNYCLOUD_ALLOW_PLAIN_HTTP_DEV=true
SUNNYCLOUD_PUBLIC_URL=$ACC_ORIGIN
SUNNYCLOUD_PUBLIC_ADDR=127.0.0.1:$ACC_API_PORT
SUNNYCLOUD_INTERNAL_ADDR=127.0.0.1:$ACC_INTERNAL_PORT
SUNNYCLOUD_OPS_ADDR=127.0.0.1:$ACC_OPS_PORT
SUNNYCLOUD_TRUSTED_PROXIES=127.0.0.1/32
SUNNYCLOUD_LOG=text
SUNNYCLOUD_OIDC_ISSUER=$ACC_ISSUER
SUNNYCLOUD_BLOB_ROOT=$MVP_DATA/blobs
SUNNYCLOUD_BLOB_FREE_RESERVE=1GiB
SUNNYCLOUD_DEFAULT_QUOTA=10GiB
SUNNYCLOUD_ACCESS_TOKEN_TTL=12h
SUNNYCLOUD_DB_API_URL_FILE=$MVP_SECRETS/db_api_url
SUNNYCLOUD_DB_MIGRATOR_URL_FILE=$MVP_SECRETS/db_migrator_url
SUNNYCLOUD_MASTER_KEY_FILE_FILE=$MVP_SECRETS/master_key_file
SUNNYCLOUD_WORKER_API_TOKEN_FILE=$MVP_SECRETS/worker_api_token
SUNNYCLOUD_SHARE_GRANT_KEY_FILE=$MVP_SECRETS/share_grant_key
SUNNYCLOUD_PROVIDER_OIDC_CLIENT_SECRET_FILE=$MVP_SECRETS/provider_oidc_client_secret
SUNNYCLOUD_WORKER_API_URL=http://127.0.0.1:$ACC_INTERNAL_PORT
SUNNYCLOUD_WORKER_OPS_LISTEN=127.0.0.1:$ACC_WORKER_OPS_PORT
SUNNYCLOUD_WORKER_SOCK_INTERACTIVE=$MVP_RUN/decoder-interactive.sock
SUNNYCLOUD_WORKER_SOCK_GENERAL=$MVP_RUN/decoder-general.sock
SUNNYCLOUD_WORKER_SCRATCH_INTERACTIVE=$MVP_DATA/scratch-interactive
SUNNYCLOUD_WORKER_SCRATCH_GENERAL=$MVP_DATA/scratch-general
ENV
  chmod 600 "$MVP_SECRETS/mvp.env"
}

# What the tests and the other scripts need to know: origin, ports and where things are. No secret.
write_acceptance_env() {
  cat > "$ACC_DATA/acceptance.env" <<ENV
ACC_HOST=$ACC_HOST
ACC_ORIGIN=$ACC_ORIGIN
ACC_WEB_PORT=$ACC_WEB_PORT
ACC_API_PORT=$ACC_API_PORT
ACC_OPS_PORT=$ACC_OPS_PORT
ACC_WORKER_OPS_PORT=$ACC_WORKER_OPS_PORT
ACC_IDP_PORT=$ACC_IDP_PORT
ACC_ISSUER=$ACC_ISSUER
ACC_DB_PORT=$ACC_DB_PORT
ACC_DB_CONTAINER=$ACC_DB_CONTAINER
ACC_CLI=$REPO_ROOT/scripts/dev/acceptance-cli.sh
ACC_API_CTL=$REPO_ROOT/scripts/dev/acceptance-api-ctl.sh
ACC_RESULTS=$ACC_RESULTS
ENV
}

# Starts a unit that is not one of the four binaries of mvp-lib: start_aux NAME WORKDIR [ENV=value ...] -- COMMAND...
start_aux() {
  local name="$1" workdir="$2" logfile
  shift 2
  local -a setenv=("--setenv=PATH=$SUPERVISED_PATH")
  while [ "$1" != -- ]; do
    setenv+=("--setenv=$1")
    shift
  done
  shift
  if unit_active "$name"; then
    log "$name already running (pid $(unit_property "$name" MainPID))"
    return 0
  fi
  [ "$(unit_property "$name" ActiveState)" = failed ] && userctl reset-failed "$(unit_of "$name")"
  logfile="$(log_file "$name")"
  systemd-run --user --quiet --unit="$(unit_of "$name")" --description="sunnycloud acceptance $name" \
    --working-directory="$workdir" --property=Restart=on-failure --property=RestartSec=1 \
    --property=StartLimitIntervalSec=0 --property=TimeoutStopSec=20 \
    --property="StandardOutput=append:$logfile" --property="StandardError=append:$logfile" \
    "${setenv[@]}" "$@"
  log "$name started under systemd --user as $(unit_of "$name") (log $logfile)"
}

# Every unit of the stack, in stop order (the worker and the decoders before the API they talk to).
all_units_stop_order() { printf '%s\n' web worker api decoder-general decoder-interactive idp; }

db_running() { [ "$(docker inspect --format '{{.State.Running}}' "$ACC_DB_CONTAINER" 2>/dev/null || true)" = true ]; }
