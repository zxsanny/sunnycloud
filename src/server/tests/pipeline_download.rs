const GIB: usize = 1024 * 1024 * 1024;
const LANES: usize = 4;
const RANGE_LEN: usize = 4096;

#[tokio::test(flavor = "multi_thread")]
#[ignore = "1 GiB: runs in the release CI job `pipelines-large` (owner decision 2026-11-18)"]
async fn ac1_a_1_gib_file_reads_in_full_by_range_past_the_end_and_conditionally() {
    // Arrange
    let pipeline = Pipeline::start(&[]).await;
    let folder = pipeline.folder("ac1");
    let file = GiantFile::new("one-gib.bin", GIB, 21);
    let blocklist = file.blocklist();
    let upload = pipeline.start_sized(folder, &file.name, file.size);
    pipeline.put_generated(upload, &file, LANES).await;
    let (node, revision) = pipeline.commit_blocklist(upload, folder, &file.name, &blocklist);
    let content_path = format!("/api/v1/nodes/{node}/content");
    let middle = file.size / 2 - RANGE_LEN / 2;

    // Act
    let metadata = pipeline.call("GET", &format!("/api/v1/revisions/{revision}"), &[], &[]);
    let full = pipeline.fetch(&content_path, &[], false);
    let ranged = pipeline.fetch(
        &content_path,
        &[(
            "Range",
            format!("bytes={middle}-{}", middle + RANGE_LEN - 1),
        )],
        true,
    );
    let past_end = pipeline.fetch(
        &content_path,
        &[("Range", format!("bytes={}-", file.size))],
        true,
    );
    let conditional = pipeline.fetch(
        &content_path,
        &[("If-None-Match", format!("\"{}\"", full.etag()))],
        true,
    );

    // Assert
    assert_eq!(metadata.status, 200, "{metadata:?}");
    let metadata = metadata.json();
    assert_eq!(metadata["size"].as_u64(), Some(GIB as u64));
    assert_eq!(metadata["content_hash"], rollup(&blocklist).to_string());
    assert_eq!(full.status, 200);
    assert!(
        full.complete(),
        "received {} of {:?}: {:?}",
        full.received,
        full.declared,
        full.cut
    );
    assert_eq!(full.file_hash, rollup(&blocklist));
    assert_eq!(full.header("accept-ranges"), Some("bytes"));
    let first_byte = full.first_byte.expect("a first byte");
    eprintln!(
        "AC-1: 1 GiB read directly, first byte after {first_byte:?}, whole body after {:?}",
        full.total
    );
    assert!(
        first_byte * 10 < full.total,
        "the body was not streamed: {first_byte:?} of {:?}",
        full.total
    );
    assert_eq!(ranged.status, 206);
    assert!(ranged.complete(), "{:?}", ranged.cut);
    assert!(
        ranged.body == file.slice(middle, RANGE_LEN),
        "the range bytes differ"
    );
    assert_eq!(
        ranged.header("content-range"),
        Some(format!("bytes {middle}-{}/{GIB}", middle + RANGE_LEN - 1).as_str())
    );
    assert_eq!(past_end.status, 416);
    assert_eq!(conditional.status, 304);
    assert_eq!(conditional.received, 0);
    pipeline.finish().await;
}

/// A PNG of `size` bytes: the 8-byte signature, then generated bytes.
fn png(size: usize) -> File {
    let mut file = File::new("picture.png", size, 61);
    file.bytes[..8].copy_from_slice(b"\x89PNG\r\n\x1a\n");
    file
}

fn html() -> File {
    let mut file = File::new("page.html", 0, 62);
    file.bytes =
        b"<!doctype html><html><body><script>alert(document.cookie)</script></body></html>\n"
            .to_vec();
    file
}

#[tokio::test(flavor = "multi_thread")]
async fn ac2_a_png_is_served_inline_and_an_html_file_as_a_sandboxed_attachment() {
    // Arrange
    let pipeline = Pipeline::start(&[]).await;
    let folder = pipeline.folder("ac2");
    let (picture, page) = (png(100 * 1024), html());
    let (picture_node, _) = pipeline.publish_small(folder, &picture, None);
    let (page_node, _) = pipeline.publish_small(folder, &page, None);

    // Act
    let inline = pipeline.fetch(&format!("/api/v1/nodes/{picture_node}/content"), &[], true);
    let attachment = pipeline.fetch(&format!("/api/v1/nodes/{page_node}/content"), &[], true);

    // Assert
    assert_eq!(inline.status, 200);
    assert!(inline.body == picture.bytes, "the PNG bytes differ");
    assert_eq!(inline.header("content-type"), Some("image/png"));
    assert_eq!(inline.header("content-disposition"), Some("inline"));
    assert_eq!(inline.header("x-content-type-options"), Some("nosniff"));
    assert_eq!(inline.header("content-security-policy"), None);
    assert_eq!(attachment.status, 200);
    assert!(attachment.body == page.bytes, "the HTML bytes differ");
    assert_eq!(
        attachment.header("content-type"),
        Some("application/octet-stream")
    );
    assert_eq!(
        attachment.header("content-disposition"),
        Some("attachment; filename*=UTF-8''page.html")
    );
    assert_eq!(attachment.header("x-content-type-options"), Some("nosniff"));
    assert_eq!(
        attachment.header("content-security-policy"),
        Some("sandbox")
    );
    pipeline.finish().await;
}

#[tokio::test(flavor = "multi_thread")]
async fn ac3_a_flipped_byte_in_a_stored_chunk_cuts_the_stream_flags_the_blob_and_logs_ids_only() {
    // Arrange: a 1 MiB file (16 chunks of 64 KiB); chunk 8 is altered on the volume.
    let pipeline = Pipeline::start(&[]).await;
    let folder = pipeline.folder("ac3");
    let file = File::new("secret-plans.bin", 1024 * 1024, 63);
    let (node, _) = pipeline.publish_small(folder, &file, None);
    let content_path = format!("/api/v1/nodes/{node}/content");
    let blob = pipeline.fetch(&content_path, &[], false).etag();
    let blob = uuid::Uuid::parse_str(&blob).expect("the ETag is the blob id");
    pipeline.flip_chunk_byte(blob, 8);

    // Act
    let corrupt = pipeline.fetch(&content_path, &[], true);

    // Assert
    assert_eq!(corrupt.status, 200);
    assert_eq!(corrupt.declared, Some(file.bytes.len() as u64));
    assert!(
        !corrupt.complete(),
        "the corrupt blob was served as a complete body"
    );
    assert!(
        corrupt.received < file.bytes.len() as u64,
        "{}",
        corrupt.received
    );
    assert!(
        corrupt.body[..] == file.bytes[..corrupt.body.len()],
        "bytes that are not the file's were served"
    );
    assert!(pipeline.blob_flagged(blob).await, "the blob is not flagged");
    let lines = pipeline.server.lines();
    let logged: Vec<_> = json_lines(&lines)
        .into_iter()
        .filter(|line| line["msg"] == "blob corrupt on read")
        .collect();
    assert_eq!(logged.len(), 1, "{lines:#?}");
    let text = logged[0].to_string();
    assert!(text.contains(&blob.to_string()), "{text}");
    assert!(!text.contains(&file.name), "{text}");
    assert!(
        lines.iter().all(|line| !line.contains(&file.name)),
        "a log line names the file"
    );
    pipeline.finish().await;
}

#[tokio::test(flavor = "multi_thread")]
async fn ac5_a_deleted_file_and_a_retained_old_revision_are_404_without_their_bytes() {
    // Arrange
    let pipeline = Pipeline::start(&[]).await;
    let folder = pipeline.folder("ac5");
    let gone = File::new("gone.bin", 4096, 64);
    let (gone_node, _) = pipeline.publish_small(folder, &gone, None);
    let first = File::new("edited.txt", 3000, 65);
    let (edited_node, old_revision) = pipeline.publish_small(folder, &first, None);
    let second = File::new("edited.txt", 3000, 66);
    let (same_node, _) = pipeline.publish_small(folder, &second, Some(old_revision));
    let deleted = pipeline.delete_file(gone_node);
    assert!((200..300).contains(&deleted.status), "{deleted:?}");

    // Act
    let deleted_read = pipeline.fetch(&format!("/api/v1/nodes/{gone_node}/content"), &[], true);
    let old_read = pipeline.fetch(
        &format!("/api/v1/revisions/{old_revision}/content"),
        &[],
        true,
    );
    let old_metadata = pipeline.call(
        "GET",
        &format!("/api/v1/revisions/{old_revision}"),
        &[],
        &[],
    );

    // Assert
    assert_eq!(same_node, edited_node);
    assert_eq!(old_metadata.status, 200, "the old revision is not retained");
    // The only body is the problem document: no content byte is served.
    for read in [&deleted_read, &old_read] {
        assert_eq!(read.status, 404, "{}", String::from_utf8_lossy(&read.body));
        assert_eq!(read.json()["code"], "not_found");
    }
    pipeline.finish().await;
}

